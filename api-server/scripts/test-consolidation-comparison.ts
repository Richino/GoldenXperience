import assert from "node:assert/strict";
import type { Candle } from "../../frontend/src/types/forex.js";
import type { ObserverRead } from "../../frontend/src/lib/market-observer-types.js";
import type { MarketAnalysis } from "../../frontend/src/lib/strategy/market-analysis.js";
import { createObserverPlan, evaluateObserverPlan, resumeObserverPlan } from "../src/market-observer-plan.js";
import { comparisonSummary, evaluateConsolidation, freezeConsolidation } from "../src/consolidation-comparison.js";
const start = Date.parse("2026-10-09T14:00:00Z"), iso = (ms = 0) => new Date(start + ms).toISOString();
const bars: Candle[] = Array.from({ length: 12 }, (_, i) => ({ time: iso((i - 12) * 300_000), open: 1.1, close: i % 2 ? 1.1001 : 1.0999, high: 1.1003, low: 1.0997, complete: true, volume: 1 }));
const frozen = freezeConsolidation("EUR_USD", bars, iso())!;
const analysis = { pair: "EUR_USD", mode: "NORMAL", v2: { analyzedAt: iso(), execution: null,
  setup: { zoneLow: null, zoneHigh: null }, watch: null, headline: "Unclear trend", invalidation: "No directional plan",
  reasoning: [], warnings: [], foundation: { primary: null } } } as unknown as MarketAnalysis;
const comparisonPlan = createObserverPlan(analysis, bars, iso(), 1);
assert.ok(comparisonPlan.consolidation, "Analyze attaches the comparison to a qualifying consolidation");
assert.equal(comparisonPlan.expiresAt, frozen.expiresAt);
const directionalAnalysis = { ...analysis, v2: { ...analysis.v2!, decision: "LONG", setup: { zoneLow: 1.0999, zoneHigh: 1.1001 },
  execution: { entry: 1.1, stop: 1.099, target: 1.102, orderLifetimeHours: 2 } } } as unknown as MarketAnalysis;
const combinedPlan = createObserverPlan(directionalAnalysis, bars, iso(), 2);
assert.ok(combinedPlan.pullback && combinedPlan.consolidation, "A qualifying box is measured alongside a directional plan");
assert.ok(frozen); assert.equal(frozen.low, 1.0997); assert.equal(frozen.high, 1.1003);
assert.equal(freezeConsolidation("EUR_USD", bars.slice(1), iso()), null);
const read = (ms: number, bid: number): ObserverRead => ({ version: "test", instrument: "EUR_USD", asOf: iso(ms), state: "live", lean: "range", headline: "Range", changedAt: iso(), revision: 1, facts: [], blockers: [], changeConditions: [],
  pressure: { direction: "range", observedDirection: "range", covered: true, pending: false, relation: "neutral" }, quote: { bid, ask: bid + 0.00002, time: iso(ms), spreadPips: 0.2 }, movement: [], patterns: [], ai: { state: "disabled", text: null, at: null, factIds: [] } });
let chop = frozen;
for (let i = 0; i < 20; i++) chop = evaluateConsolidation(chop, read(i * 1000, i % 2 ? 1.1 : 1.10062), []);
assert.equal(comparisonSummary(chop).hold.confirmations, 0, "Brief breaks followed by returns do not confirm");
let held = frozen;
for (let i = 0; i <= 10; i++) held = evaluateConsolidation(held, read(i * 1000, 1.10062), []);
assert.equal(held.attempts[0].hold.at, iso(10_000)); assert.equal(held.attempts[0].candle.at, null);
held = evaluateConsolidation(held, read(11_000, 1.1), []);
assert.equal(held.attempts[0].hold.outcome, "returned_inside", "Early hold confirmation can still be false");
let sustained = frozen;
const newBar: Candle = { ...bars[0], time: iso(), close: 1.10062, high: 1.1007, low: 1.1004, open: 1.1005 };
for (let i = 0; i <= 301; i++) sustained = evaluateConsolidation(sustained, read(i * 1000, 1.10062), [newBar]);
assert.equal(sustained.attempts[0].hold.at, iso(10_000)); assert.equal(sustained.attempts[0].candle.at, iso(300_000));
const after = evaluateConsolidation(sustained, read(302_000, 1.1009), []);
assert.equal(after.attempts[0].hold.outcome, "extended"); assert.equal(after.attempts[0].candle.outcome, "extended");
assert.deepEqual([after.low, after.high, after.buffer], [frozen.low, frozen.high, frozen.buffer]);
const attempted = evaluateConsolidation(frozen, read(0, 1.10062), []);
const duplicate = evaluateConsolidation(attempted, { ...read(4000, 1.10062), quote: read(0, 1.10062).quote }, []);
assert.equal(duplicate.attempts[0].samples, 1, "Timer passes are not new samples");
const gap = evaluateConsolidation(attempted, { ...read(6000, 1.10062), quote: null }, []);
assert.equal(gap.attempts[0].hold.outcome, "unknown");
const recovered = evaluateConsolidation(gap, read(7000, 1.10062), []);
assert.equal(recovered.attempts.length, 2, "Recovery starts a new attempt, never a continuous hold");
assert.equal(evaluateConsolidation(recovered, read(7_200_000, 1.10062), []).state, "expired");
const spreadOnly = evaluateConsolidation(frozen, { ...read(0, 1.1), quote: { ...read(0, 1.1).quote!, ask: 1.101 } }, []);
assert.equal(spreadOnly.attempts.length, 0, "A widened ask cannot invent an upward breakout");
let down = frozen;
for (let i = 0; i <= 10; i++) down = evaluateConsolidation(down, read(i * 1000, 1.09935), []);
assert.equal(down.attempts[0].side, "down"); assert.ok(down.attempts[0].hold.at);
const jumped = evaluateConsolidation(sustained, read(302_000, 1.09935), []);
assert.equal(jumped.attempts[0].hold.outcome, "unknown");
assert.equal(jumped.attempts.at(-1)!.side, "down", "A jump through the box starts a separate opposite attempt");
assert.equal(evaluateConsolidation(attempted, read(1000, 1.10062), [newBar]).attempts[0].candle.at, null, "Future candle closes cannot confirm early");
let integrated = comparisonPlan;
for (let i = 0; i <= 10; i++) integrated = evaluateObserverPlan(integrated, { ...read(i * 1000, 1.10062), blockers: ["News coverage unknown"] }, []);
assert.ok(integrated.consolidation!.attempts[0].hold.at, "Shadow observations continue independently of entry gates");
assert.deepEqual(integrated.consolidation!.attempts[0].hold.blockers, ["News coverage unknown"]);
assert.equal(integrated.triggeredAt, null, "A shadow confirmation never becomes an entry signal");
assert.equal(resumeObserverPlan(integrated, iso(11_000)).consolidation!.attempts[0].hold.outcome, "unknown", "Restart cannot infer the intervening path");
console.log(JSON.stringify({ syntheticMechanismCheckOnly: true, chop: comparisonSummary(chop), failedHold: comparisonSummary(held), sustained: comparisonSummary(after) }, null, 2));
