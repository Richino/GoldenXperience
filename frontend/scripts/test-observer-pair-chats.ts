import assert from "node:assert/strict";
import { appendObserverPairMessages, markObserverPairRead, OBSERVER_CHAT_MESSAGE_LIMIT, type ObserverPairChats } from "../src/lib/observer-pair-chats";
import type { ObserverChatMessage } from "../src/lib/observer-conversation";

const message = (instrument: string, id: string, role: ObserverChatMessage["role"] = "observer"): ObserverChatMessage => ({ instrument, id, role, at: "2026-10-10T16:00:00Z", kind: role === "user" ? "request" : "read", text: `${instrument}: ${id}`, evidence: [{ id, text: `Evidence for ${instrument}` }] });
let chats: ObserverPairChats = {};
chats = appendObserverPairMessages(chats, [message("AUD_JPY", "a1"), message("USD_CHF", "c1"), message("AUD_JPY", "a2")], "AUD_JPY");
assert.deepEqual(chats.AUD_JPY.messages.map(m => m.id), ["a1", "a2"]);
assert.deepEqual(chats.USD_CHF.messages.map(m => m.id), ["c1"]);
assert.equal(chats.AUD_JPY.unread, 0, "Reading one chat acknowledges its new observations");
assert.equal(chats.USD_CHF.unread, 1, "A different pair's updates remain unread");
const originalAudChat = chats.AUD_JPY;
const originalChfChat = chats.USD_CHF;
chats = appendObserverPairMessages(chats, Array.from({ length: 150 }, (_, i) => message("USD_CHF", `c${i + 2}`)), "AUD_JPY");
assert.equal(chats.AUD_JPY, originalAudChat, "Busy pairs cannot replace or evict a quieter pair's history");
assert.equal(originalChfChat.messages.length, 1, "Appending preserves previous state and frozen evidence");
assert.equal(chats.USD_CHF.messages.length, OBSERVER_CHAT_MESSAGE_LIMIT);
assert.equal(chats.USD_CHF.messages[0].id, "c32");
assert.equal(chats.USD_CHF.unread, OBSERVER_CHAT_MESSAGE_LIMIT, "Unread stays bounded to retained history");
const unreadChats = chats;
chats = markObserverPairRead(chats, "USD_CHF");
assert.equal(chats.USD_CHF.unread, 0);
assert.equal(unreadChats.USD_CHF.unread, OBSERVER_CHAT_MESSAGE_LIMIT, "Reading a chat does not mutate prior state");
assert.equal(chats.AUD_JPY, originalAudChat);
assert.equal(markObserverPairRead(chats, "USD_CHF"), chats, "Acknowledgement is idempotent");
assert.equal(markObserverPairRead(chats, "EUR_USD"), chats);
chats = appendObserverPairMessages(chats, [message("AUD_JPY", "request", "user")], null);
assert.equal(chats.AUD_JPY.unread, 0, "Own requests do not count as unread observations");
chats = appendObserverPairMessages(chats, [message("AUD_JPY", "older-history-update"), message("USD_CHF", "background-update")], null);
assert.equal(chats.AUD_JPY.unread, 1, "Closed chats or chats scrolled into history retain unread observations");
assert.equal(chats.USD_CHF.unread, 1);
chats = markObserverPairRead(chats, "AUD_JPY");
assert.equal(chats.USD_CHF.unread, 1, "Switching chats cannot clear another pair's unread count");
assert.equal(appendObserverPairMessages(chats, [], null), chats);
console.log("Observer pair chat tests passed: isolated histories, independent retention, unread routing, acknowledgements, immutable evidence and bounded counts.");
