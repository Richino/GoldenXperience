import assert from "node:assert/strict";
import { aggregateR, createPlannedRiskBudget, equityDrawdownUsd, formatRMultiple, monetaryRatio, netPnlUsd, observedExcursions, partialCloseR, riskMetrics, verifiedRStatistics, verifiedTradeR, type InitialRiskPlan } from "../src/lib/risk-metrics";
const plan: InitialRiskPlan = Object.freeze({ version: 1, positionKey: "entry-a", recordedAt: "2026-10-28T12:00:00Z", currency: "USD", initialPlannedRiskUsd: 1000, entryEquityUsd: 100000, plannedNetRewardUsd: null, source: "explicit_budget" });
const metrics = (pnl: number, risk: InitialRiskPlan | null = plan) => riskMetrics({ plan: risk, positionKey: "entry-a", openedAt: "2026-10-28T12:01:00Z", realizedNetPnlUsd: pnl });
assert.equal(metrics(1000).realizedRMultiple, 1);
assert.equal(metrics(-2500).realizedRMultiple, -2.5);
assert.equal(metrics(500, { ...plan, initialPlannedRiskUsd: 2000 }).realizedRMultiple, 0.25);
assert.equal(metrics(500, null).realizedRMultiple, null);
assert.equal(metrics(500, { ...plan, initialPlannedRiskUsd: 0 }).realizedRMultiple, null);
assert.equal(metrics(500, { ...plan, initialPlannedRiskUsd: -1000 }).realizedRMultiple, null);
assert.equal(metrics(500, { ...plan, recordedAt: "2026-10-28T12:02:00Z" }).realizedRMultiple, null, "late stop/budget cannot establish original risk");
assert.equal(metrics(500).realizedRMultiple, .5, "a protective stop is not required for an explicit budget");
assert.equal(metrics(500).plannedRewardRiskRatio, null);
assert.equal(metrics(500, { ...plan, plannedNetRewardUsd: 2000 }).plannedRewardRiskRatio, 2);
assert.equal(metrics(500).realizedReturnPct, .5);
const newPlan = createPlannedRiskBudget({ value: 1, unit: "percent", equityBeforeEntryUsd: 100000, recordedAt: plan.recordedAt, positionKey: "entry-a", brokerAccountId: "practice-account", plannedNetRewardUsd: null });
assert.equal(newPlan.initialPlannedRiskUsd, 1000);
assert.equal(Object.isFrozen(newPlan), true);
assert.equal("stop" in newPlan, false, "recording an accounting budget must not create a protective stop");
const reopened = JSON.parse(JSON.stringify({ id: "a", riskPositionKey: "entry-a", openedAt: "2026-10-28T12:01:00Z", initialRiskPlan: newPlan, realizedNetPnlUsd: 750, resultR: 6.22, stop: null }));
assert.equal(verifiedTradeR(reopened).resultR, .75);
assert.equal(verifiedTradeR({ ...reopened, stop: 1.08 }).resultR, .75, "adding or moving a later stop must not change original R");
assert.equal(equityDrawdownUsd([]), null);
assert.equal(equityDrawdownUsd([{ at: plan.recordedAt, adjustedEquityUsd: 1000 }, { at: "2026-10-28T12:01:00Z", adjustedEquityUsd: 800 }, { at: "2026-10-28T12:02:00Z", adjustedEquityUsd: 1200 }]), 200);
assert.equal(riskMetrics({ plan, positionKey: "another-position", openedAt: "2026-10-28T12:01:00Z", realizedNetPnlUsd: 500 }).realizedRMultiple, null);
assert.equal(partialCloseR(1000, 100, [{ units: 25, netPnlUsd: 250 }, { units: 25, netPnlUsd: -500 }]), -.5);
assert.equal(partialCloseR(1000, 100, [{ units: 101, netPnlUsd: 20 }]), null);
assert.equal(aggregateR([{ key: "a", netPnlUsd: 1000, initialRiskUsd: 1000 }, { key: "b", netPnlUsd: 0, initialRiskUsd: 3000 }]), .25, "portfolio R must not average individual R");
assert.equal(aggregateR([{ key: "a", netPnlUsd: 1, initialRiskUsd: 100 }, { key: "a", netPnlUsd: 1, initialRiskUsd: 100 }]), null);
assert.equal(aggregateR([{ key: "a", netPnlUsd: 1, initialRiskUsd: null }]), null);
assert.equal(netPnlUsd(2000, -20, 10, 0, .5), 985);
assert.equal(netPnlUsd(2000, null, 10, 0, .5), null);
assert.equal(monetaryRatio(.3, .1), 3);
assert.equal(monetaryRatio(1e-20, 1), 1e-20, "preserve tiny positive R until presentation");
assert.equal(monetaryRatio(-1e-20, 1), -1e-20, "preserve tiny negative R for outcome statistics");
assert.equal(monetaryRatio(1e308, 1), 1e308);
assert.equal(monetaryRatio(1e308, 1e-308), null, "unrepresentable ratios must not produce Infinity");
assert.equal(monetaryRatio(1e-308, 1e308), null, "unrepresentable nonzero ratios must not become zero");
assert.equal(formatRMultiple(null), "N/A — initial risk not recorded");
assert.equal(formatRMultiple(-2.5), "−2.50R");
assert.equal(formatRMultiple(NaN), "N/A — initial risk not recorded");
const legacy = { id: "legacy", openedAt: "2026-10-14T12:00:00Z", resultR: 6.22, paperPl: 1196 };
const corrected = verifiedTradeR(legacy);
assert.equal(corrected.resultR, null);
assert.equal(corrected.legacyR, 6.22);
assert.equal(verifiedTradeR(corrected).legacyR, 6.22, "reprojection must preserve original legacy evidence");
assert.equal(verifiedTradeR(verifiedTradeR(reopened)).legacyR, 6.22);
assert.equal(corrected.paperPl, 1196);
assert.equal(legacy.resultR, 6.22, "read projection cannot mutate historical evidence");
assert.equal(verifiedTradeR(JSON.parse(JSON.stringify(legacy))).resultR, null, "reloads cannot promote legacy R");
const stats = verifiedRStatistics([{ ...corrected }, { resultR: 1, paperPl: 1000, riskDataQuality: "verified" }]);
assert.equal(stats.included, 1); assert.equal(stats.excluded, 1); assert.equal(stats.realizedPnlUsd, 2196); assert.equal(stats.expectancyR, null); assert.equal(stats.winRate, 1);
const excursions = observedExcursions(1.1, "long", .0001, [
  { at: "2026-10-28T12:01:00Z", units: 10000, bid: 1.09, ask: 1.0902, netFloatingPnlUsd: -100 },
  { at: "2026-10-28T12:02:00Z", units: 1000, bid: 1.08, ask: 1.0802, netFloatingPnlUsd: -20 },
]);
assert.equal(excursions.maxAdverseExcursionUsd, 100, "use each observation's real exposure, never final size across the path");
assert.equal(riskMetrics({ plan, positionKey: "entry-a", openedAt: "2026-10-28T12:01:00Z", realizedNetPnlUsd: 200, maxAdverseExcursionUsd: 0 }).drawdownAdjustedResult, null);
assert.equal(riskMetrics({ plan, positionKey: "entry-a", openedAt: "2026-10-28T12:01:00Z", maxAdverseExcursionUsd: 0 }).maeR, 0);
console.log("Risk metrics passed: signed R, no-stop budgets, late/missing evidence, targetless plans, partials, independent additions, currency/cost completeness, legacy preservation, coverage, reloads and observed variable exposure.");
